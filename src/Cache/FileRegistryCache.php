<?php

declare(strict_types=1);

namespace Gcego\Registry\Cache;

use Closure;
use Gcego\Registry\Contracts\RegistryCache;
use Gcego\Registry\Exceptions\RegistryCacheException;
use Illuminate\Filesystem\Filesystem;
use Throwable;

/**
 * Stores the manifest as a PHP file returning an array, like Laravel's own
 * bootstrap caches (opcache-friendly, no unserialize()).
 *
 * Only arrays of scalars are ever written (var_export of Manifest::toArray()),
 * and reads verify structure and checksum before use. Writes go to a
 * temporary file that is renamed into place, so concurrent readers never see
 * a partial manifest; rebuilds are serialized with an exclusive file lock.
 * The ".lock" file is kept on purpose: deleting it while another process
 * waits on it would let two rebuilds run at once.
 */
final readonly class FileRegistryCache implements RegistryCache
{
    public function __construct(
        private string $path,
        private Filesystem $files = new Filesystem,
    ) {}

    public function path(): string
    {
        return $this->path;
    }

    public function exists(): bool
    {
        return is_file($this->path);
    }

    public function read(): ?Manifest
    {
        if (! is_file($this->path)) {
            return null;
        }

        try {
            $data = (static fn (string $__gcegoRegistryCache): mixed => require $__gcegoRegistryCache)($this->path);
        } catch (Throwable $exception) {
            throw RegistryCacheException::corrupt($this->path, 'unreadable PHP: '.$exception->getMessage(), $exception);
        }

        return Manifest::fromArray($data, $this->path);
    }

    public function write(Manifest $manifest): void
    {
        $contents = "<?php\n\n// Generated by gcego/registry. Do not edit; rebuild with php artisan gcego:registry-cache.\n\nreturn "
            .var_export($manifest->toArray(), true).";\n";

        try {
            $this->files->ensureDirectoryExists(dirname($this->path));
            $this->files->replace($this->path, $contents);
        } catch (Throwable $exception) {
            throw RegistryCacheException::unwritable($this->path, $exception);
        }

        $this->forgetOpcache();
    }

    public function clear(): bool
    {
        if (! is_file($this->path)) {
            return false;
        }

        $deleted = @unlink($this->path);
        $this->forgetOpcache();

        return $deleted;
    }

    public function locked(Closure $callback): mixed
    {
        $this->files->ensureDirectoryExists(dirname($this->path));
        $handle = @fopen($this->path.'.lock', 'c');

        if ($handle === false) {
            throw RegistryCacheException::unwritable($this->path.'.lock');
        }

        if (! flock($handle, LOCK_EX)) {
            fclose($handle);

            throw RegistryCacheException::unlockable($this->path.'.lock');
        }

        try {
            return $callback();
        } finally {
            flock($handle, LOCK_UN);
            fclose($handle);
        }
    }

    private function forgetOpcache(): void
    {
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($this->path, true);
        }
    }
}
